#ifndef NVTX_COLORS_H
#define NVTX_COLORS_H

// Format : 0xAARRGGBB (Alpha, Rouge, Vert, Bleu)

#define NVTX_COLOR_RED     0xFFFF0000u  // Rouge
#define NVTX_COLOR_BLUE    0xFF0000FFu  // Bleu
#define NVTX_COLOR_YELLOW  0xFFFFFF00u  // Jaune
#define NVTX_COLOR_GREEN   0xFF00FF00u  // Vert
#define NVTX_COLOR_ORANGE  0xFFFF8800u  // Orange
#define NVTX_COLOR_PURPLE  0xFFAA00FFu  // Violet
#define NVTX_COLOR_CYAN    0xFF00FFFFu  // Cyan
#define NVTX_COLOR_WHITE   0xFFFFFFFFu  // Blanc
#define NVTX_COLOR_GRAY    0xFF888888u  // Gris

 #endif // NVTX_COLORS_H
